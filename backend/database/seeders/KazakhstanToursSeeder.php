Шымкент — второй по численности населения город Казахстана. Древнее городище в его центре гармонично сочетается с современной архитектурой, сохраняя богатое историческое наследие. Это идеальное место, чтобы познакомиться с южным гостеприимством.
Шымкент был основан в XII веке как караван-сарай (древние гостиницы на Великом шелковом пути) для защиты города Сайрам, расположенного в 20 км к югу, на границе с Узбекистаном. Со временем Шымкент стал крупным торговым центром, где велась торговля между тюркскими кочевниками и оседлыми согдийцами (древней цивилизацией, которая в разные периоды включала территории современного Узбекистана и Таджикистана).
Экскурсия по Шымкенту начинается с посещения одной из главных достопримечательностей города — Парка Независимости, где расположены площадь Ордабасы и монумент «Жер-Ана».
Затем экскурсия продолжится к загадочной реке Кошкар-Ата. Во время экскурсии вы узнаете, как источник этой реки стал источником возникновения города и кем был Кошкар-Ата. Здесь вы сможете попробовать воду из священного целебного источника. Это место считается не только священным, но и одним из самых любимых мест отдыха жителей города.
Далее вы познакомитесь с самой древней частью Шымкента, посетив Цитадель. По мнению ученых, возраст Шымкента превышает 2000 лет.
Также вы посетите одно из самых уникальных мест города — Этнографический музей. Вся экспозиция и помещения музея созданы руками одного человека. Он воссоздал более 10 музыкальных инструментов, различные глиняные предметы быта, кувшины, которые полностью отражают древний быт казахов и традиции, навсегда сохранившиеся в национальной культуре. Часть музея расположена под землей и представляет собой хильвет — подземную мечеть.
В завершение экскурсии вы отправитесь к памятнику Байдибек би, откуда открывается прекрасный панорамный вид на город.
